// Generates src/types/contract/* from docs/schemas, so the UI cannot drift.
// One module per schema: compiling them into a single file collides, because
// run_result.json also defines Evidence, Link and Verdict.
// Usage: node scripts/gen-types.mjs [--check]
import { compile } from "json-schema-to-typescript";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, "../../docs/schemas");
const outDir = path.resolve(here, "../src/types/contract");
const check = process.argv.includes("--check");

const MODULES = [
  { file: "evidence.json", name: "Evidence", out: "evidence" },
  { file: "link.json", name: "Link", out: "link" },
  { file: "verdict.json", name: "Verdict", out: "verdict" },
  { file: "event.json", name: "Event", out: "event" },
  { file: "run_result.json", name: "RunResult", out: "run_result" },
];

const BANNER = `/* eslint-disable */
/**
 * GENERATED from docs/schemas/%FILE% by scripts/gen-types.mjs. Do not edit.
 */`;

async function build() {
  const modules = new Map();
  for (const entry of MODULES) {
    const raw = JSON.parse(await readFile(path.join(schemaDir, entry.file), "utf8"));
    const body = await compile(raw, entry.name, {
      bannerComment: BANNER.replace("%FILE%", entry.file),
      additionalProperties: false,
      declareExternallyReferenced: true,
      style: { semi: true, singleQuote: false },
    });
    modules.set(entry.out, body.trimEnd() + "\n");
  }

  const barrel = `/* eslint-disable */
/**
 * GENERATED by scripts/gen-types.mjs. Do not edit.
 * The wire contract, straight from docs/schemas.
 */
export type { Evidence } from "./evidence";
export type { Link } from "./link";
export type { Verdict } from "./verdict";
export type { Event } from "./event";
export type { RunResult } from "./run_result";
`;
  modules.set("index", barrel);
  return modules;
}

const modules = await build();

if (check) {
  let stale = false;
  for (const [name, content] of modules) {
    const file = path.join(outDir, `${name}.ts`);
    if (!existsSync(file)) {
      console.error(`missing ${path.relative(process.cwd(), file)}`);
      stale = true;
      continue;
    }
    if ((await readFile(file, "utf8")) !== content) {
      console.error(`stale ${path.relative(process.cwd(), file)}`);
      stale = true;
    }
  }
  if (stale) {
    console.error("run npm run types");
    process.exit(1);
  }
  console.log("types match docs/schemas");
  process.exit(0);
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
for (const [name, content] of modules) {
  await writeFile(path.join(outDir, `${name}.ts`), content);
}
console.log(`wrote ${modules.size} files to ${path.relative(process.cwd(), outDir)}`);
